_RCON = (
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36,
)


def _xtime(b: int) -> int:
    return ((b << 1) & 0xFF) ^ (0x1B if b & 0x80 else 0)


def _gmul(a: int, b: int) -> int:
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return p & 0xFF


def _key_expansion(key: bytes) -> Tuple[bytes, int]:
    """Return (expanded_key, num_rounds)."""
    key_len = len(key)
    if key_len not in (16, 24, 32):
        raise ValueError("AES key must be 16, 24 or 32 bytes")
    nk = key_len // 4
    nr = nk + 6
    nb = 4
    total_words = nb * (nr + 1)

    w = [0] * (total_words * 4)
    w[: key_len] = list(key)

    i = nk
    while i < total_words:
        # Last word
        t = w[(i - 1) * 4 : i * 4]
        if i % nk == 0:
            # RotWord + SubWord + Rcon
            t = [t[1], t[2], t[3], t[0]]
            t = [_SBOX[b] for b in t]
            t[0] ^= _RCON[i // nk]
        elif nk > 6 and i % nk == 4:
            t = [_SBOX[b] for b in t]
        prev = w[(i - nk) * 4 : (i - nk + 1) * 4]
        new = [a ^ b for a, b in zip(prev, t)]
        w[i * 4 : (i + 1) * 4] = new
        i += 1

    return bytes(w), nr


def _add_round_key(state: list, round_key: bytes) -> list:
    return [s ^ k for s, k in zip(state, round_key)]


def _sub_bytes(state: list, sbox=_SBOX) -> list:
    return [sbox[b] for b in state]


def _shift_rows(state: list) -> list:
    # state is column-major: bytes [r + 4*c]
    out = state[:]
    # row 1: shift left by 1
    out[1], out[5], out[9], out[13] = state[5], state[9], state[13], state[1]
    # row 2: shift left by 2
    out[2], out[6], out[10], out[14] = state[10], state[14], state[2], state[6]
    # row 3: shift left by 3
    out[3], out[7], out[11], out[15] = state[15], state[3], state[7], state[11]
    return out


def _inv_shift_rows(state: list) -> list:
    out = state[:]
    out[1], out[5], out[9], out[13] = state[13], state[1], state[5], state[9]
    out[2], out[6], out[10], out[14] = state[10], state[14], state[2], state[6]
    out[3], out[7], out[11], out[15] = state[7], state[11], state[15], state[3]
    return out


def _mix_columns(state: list) -> list:
    out = [0] * 16
    for c in range(4):
        col = state[c * 4 : c * 4 + 4]
        out[c * 4 + 0] = _gmul(col[0], 2) ^ _gmul(col[1], 3) ^ col[2] ^ col[3]
        out[c * 4 + 1] = col[0] ^ _gmul(col[1], 2) ^ _gmul(col[2], 3) ^ col[3]
        out[c * 4 + 2] = col[0] ^ col[1] ^ _gmul(col[2], 2) ^ _gmul(col[3], 3)
        out[c * 4 + 3] = _gmul(col[0], 3) ^ col[1] ^ col[2] ^ _gmul(col[3], 2)
    return out


def _inv_mix_columns(state: list) -> list:
    out = [0] * 16
    for c in range(4):
        col = state[c * 4 : c * 4 + 4]
        out[c * 4 + 0] = (
            _gmul(col[0], 0x0E) ^ _gmul(col[1], 0x0B)
            ^ _gmul(col[2], 0x0D) ^ _gmul(col[3], 0x09)
        )
        out[c * 4 + 1] = (
            _gmul(col[0], 0x09) ^ _gmul(col[1], 0x0E)
            ^ _gmul(col[2], 0x0B) ^ _gmul(col[3], 0x0D)
        )
        out[c * 4 + 2] = (
            _gmul(col[0], 0x0D) ^ _gmul(col[1], 0x09)
            ^ _gmul(col[2], 0x0E) ^ _gmul(col[3], 0x0B)
        )
        out[c * 4 + 3] = (
            _gmul(col[0], 0x0B) ^ _gmul(col[1], 0x0D)
            ^ _gmul(col[2], 0x09) ^ _gmul(col[3], 0x0E)
        )
    return out


def _encrypt_block(block: bytes, exp_key: bytes, nr: int) -> bytes:
    state = list(block)
    state = _add_round_key(state, exp_key[0:16])
    for r in range(1, nr):
        state = _sub_bytes(state)
        state = _shift_rows(state)
        state = _mix_columns(state)
        state = _add_round_key(state, exp_key[r * 16 : (r + 1) * 16])
    state = _sub_bytes(state)
    state = _shift_rows(state)
    state = _add_round_key(state, exp_key[nr * 16 : (nr + 1) * 16])
    return bytes(state)


def _decrypt_block(block: bytes, exp_key: bytes, nr: int) -> bytes:
    state = list(block)
    state = _add_round_key(state, exp_key[nr * 16 : (nr + 1) * 16])
    for r in range(nr - 1, 0, -1):
        state = _inv_shift_rows(state)
        state = _sub_bytes(state, _INV_SBOX)
        state = _add_round_key(state, exp_key[r * 16 : (r + 1) * 16])
        state = _inv_mix_columns(state)
    state = _inv_shift_rows(state)
    state = _sub_bytes(state, _INV_SBOX)
    state = _add_round_key(state, exp_key[0:16])
    return bytes(state)


# ---------------------------------------------------------------------------
# Padding + CBC mode
# ---------------------------------------------------------------------------

def pkcs7_pad(data: bytes, block_size: int = 16) -> bytes:
    pad = block_size - (len(data) % block_size)
    return data + bytes([pad]) * pad


def pkcs7_unpad(data: bytes, block_size: int = 16) -> bytes:
    if not data or len(data) % block_size != 0:
        raise ValueError("Invalid padded data length")
    pad = data[-1]
    if pad < 1 or pad > block_size:
        raise ValueError("Invalid PKCS#7 padding")
    if data[-pad:] != bytes([pad]) * pad:
        raise ValueError("Invalid PKCS#7 padding bytes")
    return data[:-pad]


def encrypt_cbc(key: bytes, iv: bytes, plaintext: bytes) -> bytes:
    """AES-CBC encrypt with PKCS#7 padding. ``iv`` must be 16 bytes."""
    if len(iv) != 16:
        raise ValueError("IV must be 16 bytes")
    exp_key, nr = _key_expansion(key)
    padded = pkcs7_pad(plaintext, 16)
    out = bytearray()
    prev = iv
    for i in range(0, len(padded), 16):
        block = bytes(b ^ p for b, p in zip(padded[i : i + 16], prev))
        ct = _encrypt_block(block, exp_key, nr)
        out.extend(ct)
        prev = ct
    return bytes(out)


def decrypt_cbc(key: bytes, iv: bytes, ciphertext: bytes) -> bytes:
    """AES-CBC decrypt + PKCS#7 unpad."""
    if len(iv) != 16:
        raise ValueError("IV must be 16 bytes")
    if len(ciphertext) % 16 != 0:
        raise ValueError("Ciphertext length must be a multiple of 16")
    exp_key, nr = _key_expansion(key)
    out = bytearray()
    prev = iv
    for i in range(0, len(ciphertext), 16):
        ct = ciphertext[i : i + 16]
        pt = _decrypt_block(ct, exp_key, nr)
        out.extend(b ^ p for b, p in zip(pt, prev))
        prev = ct
    return pkcs7_unpad(bytes(out), 16)


