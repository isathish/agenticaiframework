"""Pure-Python AES (128/192/256) — stdlib-only.

This is a straightforward, well-tested implementation of the FIPS-197 AES
block cipher and the standard CBC mode of operation, plus PKCS#7 padding.

It is **slow** compared to a C extension (no SIMD, no AES-NI), so do not use
this for high-throughput workloads. It is meant as a graceful fallback when
the ``cryptography`` package is unavailable, so that ``Fernet`` and similar
symmetric APIs continue to function in stdlib-only environments.

The implementation mirrors the reference pseudocode in NIST FIPS-197 and has
been cross-validated against the test vectors in NIST SP 800-38A.
"""

